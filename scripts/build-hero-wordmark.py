"""Build the smooth hero wordmark as inline vectors (no runtime font wait).
Requires fonttools and brotli. Run from any directory to update index.html.
"""
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

root = Path(__file__).resolve().parents[1]
font = instantiateVariableFont(TTFont(root / 'fonts/Inter-Latin-Variable.woff2'), {'wght': 720})
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
scale = 1000 / font['head'].unitsPerEm
word = 'whynicky'
x = 0
paths = []
for char in word:
    name = cmap[ord(char)]
    pen = SVGPathPen(glyphs, ntos=lambda n: f'{n:.2f}'.rstrip('0').rstrip('.'))
    glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x, 800)))
    paths.append(f'<path d="{pen.getCommands()}"/>')
    x += font['hmtx'][name][0] * scale - 38
# Raised registration symbol, aligned to the ascender rather than the baseline.
name = cmap[ord('®')]
bounds = BoundsPen(glyphs)
glyphs[name].draw(bounds)
reg_scale = 290 / (bounds.bounds[3] - bounds.bounds[1])
pen = SVGPathPen(glyphs, ntos=lambda n: f'{n:.2f}'.rstrip('0').rstrip('.'))
glyphs[name].draw(TransformPen(pen, (reg_scale, 0, 0, -reg_scale, x + 65, 60 + bounds.bounds[3] * reg_scale)))
paths.append(f'<path d="{pen.getCommands()}"/>')
width = round(x + 100 + font['hmtx'][name][0] * reg_scale)
lines = [f'<svg class="hero-word" viewBox="0 0 {width} 1040" aria-hidden="true" focusable="false">', '<defs>', '<g id="hero-lettering">', *paths, '</g>']
for row in range(6):
    lines.append(f'<clipPath id="hero-band-{row}" clipPathUnits="userSpaceOnUse"><rect x="-1000" y="{row*180-20}" width="{width+2000}" height="180"/></clipPath>')
lines += ['</defs>', '<use class="hero-solid" href="#hero-lettering"/>']
for row in range(6):
    dx = (1 if row % 2 else -1) * (200 + row * 70)
    lines.append(f'<g class="hero-slice" style="--piece-x:{dx}px;--piece-delay:{row*65}ms"><g clip-path="url(#hero-band-{row})"><use href="#hero-lettering"/></g></g>')
lines.append('</svg>')
page = root / 'index.html'
s = page.read_text()
start = s.index('        <h1 id="hero-title"')
end = s.index('</h1>', start) + len('</h1>')
s = s[:start] + '        <h1 id="hero-title" aria-label="whynicky®">\n          <!-- Inline wordmark: generated by scripts/build-hero-wordmark.py. -->\n' + '\n'.join(lines) + '\n        </h1>' + s[end:]
page.write_text(s)
print(f'Smooth {word}® wordmark: six bands, {width} unit width')
